local Core=dofile('portable/core.lua')
assert(type(Core.beginDanceMeter)=='function','Dance meter and speed stages must exist')
local count=0
local function test(name,fn)fn();count=count+1;print('PASS dance speed: '..name)end
local function setup()
    local c=Core.new({InteractDistance=6,DownDuration=18});local a,v=c:register('a'),c:register('v')
    v.downed=true;v.ragdolled=true;v.health=42;v.recoverAt=20
    assert(c:dance(a,v,0,1,4));assert(c:beginDanceMeter(a,0));return c,a,v
end
test('source pulses fill the meter and preserve the running interaction',function()
    local c,a,v=setup();c:tick(4);local view=c:danceMeterView(a)
    assert(view.progress==0.1 and view.stage==1 and not view.ready and view.speed==1 and a.busy)
    c:tick(10.4);assert(c:danceMeterView(a).progress==0.26 and c:danceMeterView(a).ready)
end)
test('early spam and invalid times cannot accelerate the pair',function()
    local c,a=setup();assert(not c:advanceDance(a,0));assert(not c:advanceDance(a,0/0));assert(not c:advanceDance(a,math.huge))
    c:tick(10.4);assert(c:advanceDance(a,10.4));assert(not c:advanceDance(a,10.4));assert(c:danceMeterView(a).stage==2)
end)
test('only the initiating record can control the meter',function()
    local c,a,v=setup();local third=c:register('third');c:tick(11)
    assert(not c:danceMeterView(v) and not c:danceMeterView(third))
    assert(not c:advanceDance(v,11) and not c:advanceDance(third,11));assert(c:advanceDance(a,11))
end)
test('stages retain source thresholds and pulse acceleration',function()
    local c,a=setup();assert(c:advanceDance(a,10.4));local m=c:danceMeterView(a)
    assert(m.stage==2 and m.speed==7);c:tick(15.84)
    assert(c:danceMeterView(a).progress==0.6 and c:danceMeterView(a).ready);assert(c:advanceDance(a,15.84))
    c:tick(18.4);assert(c:danceMeterView(a).progress==1 and c:danceMeterView(a).ready and c:danceMeterView(a).stage==3)
end)
test('full meter finishes without damage scoring or stale control',function()
    local c,a,v=setup();c:tick(40);assert(c:advanceDance(a,40))
    assert(not a.busy and not v.busy and v.health==42 and a.kills==0 and not v.virtualDead)
    assert(not c:danceMeterView(a) and not c:advanceDance(a,41) and v.ragdolled)
end)
test('an unused release input expires after sixty seconds',function()
    local c,a,v=setup();c:tick(59.9);assert(a.busy);c:tick(60)
    assert(not a.dance and not v.busy and v.health==42 and a.kills==0)
end)
test('stopping resets the meter for the next pair',function()
    local c,a,v=setup();c:tick(12);assert(c:stopDance(a,12));assert(not c:danceMeterView(a))
    assert(c:dance(a,v,13,1,4));assert(c:beginDanceMeter(a,13));assert(c:danceMeterView(a).progress==0)
    assert(not c:beginDanceMeter(a,14),'A repeated begin must not reset or extend an active meter')
end)
test('departure releases peer and a new generation cannot inherit the meter',function()
    local c,a,v=setup();c:detach(a,1);local fresh=c:register('a')
    assert(not c:danceMeterView(fresh) and not v.busy and not v.dance)
end)
print('DANCE SPEED STATE TESTS '..count)
