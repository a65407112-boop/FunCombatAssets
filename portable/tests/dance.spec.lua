local Core=dofile('portable/core.lua')
assert(type(Core.dance)=='function','Paired dance must be implemented in the virtual core')
local count=0
local function test(name,fn)fn();count=count+1;print('PASS dance: '..name)end
local function setup()
    local c=Core.new({InteractDistance=6,DownDuration=18})
    local a,v=c:register('actor'),c:register('target');v.downed=true;v.ragdolled=true;v.health=42;v.recoverAt=10
    return c,a,v
end
test('only a nearby available downed target can join',function()
    local c,a,v=setup();assert(c:canDance(a,v,6));assert(not c:canDance(a,v,7))
    for _,distance in ipairs({-1,math.huge,0/0})do assert(not c:canDance(a,v,distance))end
    assert(not c:canDance(a,a,0));assert(not c:canDance(nil,v,1))
    v.downed=false;v.ragdolled=false;assert(not c:canDance(a,v,1))
end)
test('busy carried dead and stale targets cannot join',function()
    local c,a,v=setup()
    for _,flag in ipairs({'busy','carriedBy','carrying','virtualDead'})do v[flag]=true;assert(not c:canDance(a,v,1));v[flag]=nil end
    a.busy=true;assert(not c:canDance(a,v,1));a.busy=false
    c:detach(v,0);local fresh=c:register('target');fresh.downed=true
    assert(not c:canDance(a,v,1));assert(c:canDance(a,fresh,1))
end)
test('invalid time and duration never start an interaction',function()
    local c,a,v=setup()
    for _,duration in ipairs({0,-1,31,math.huge,0/0})do assert(not c:dance(a,v,0,1,duration))end
    assert(not c:dance(a,v,0/0,1,4));assert(not a.busy and not v.busy and not a.dance)
end)
test('dance reserves both records without causing damage or score',function()
    local c,a,v=setup();a.attack={};v.attack={};assert(c:dance(a,v,2,1,4))
    assert(a.dance==v.dance and a.busy and v.busy and not v.ragdolled and not v.recoverAt)
    assert(not a.attack and not v.attack and not c:free(a) and not c:canCarry(a,v,1) and not c:canGlory(a,v,1))
    assert(v.health==42 and a.kills==0 and not v.virtualDead and not a.link and not v.link)
end)
test('only its initiator can select Stop',function()
    local c,a,v=setup();local third=c:register('third');assert(c:dance(a,v,2,1,4))
    assert(not c:stopDance(v,3));assert(not c:stopDance(third,3));assert(not c:stopDance(a,0/0));assert(a.busy)
    assert(c:stopDance(a,3));assert(not c:stopDance(a,3));assert(not a.busy and not v.busy)
end)
test('Stop restores target state and pauses its recovery timer',function()
    local c,a,v=setup();assert(c:dance(a,v,2,1,4));assert(c:stopDance(a,3))
    assert(v.downed and v.ragdolled and v.recoverAt==11 and v.health==42 and a.kills==0)
    c:tick(10);assert(v.downed);c:tick(11);assert(not v.downed and not v.ragdolled)
end)
test('a briefly ragdolled target keeps its original health and flags',function()
    local c,a,v=setup();v.downed=false;v.recoverAt=2.5
    assert(c:dance(a,v,2,1,4));assert(c:stopDance(a,3))
    assert(not v.downed and v.ragdolled and v.health==42 and v.recoverAt==3.5)
    c:tick(3.5);assert(not v.ragdolled and v.health==42)
end)
test('one clip completes and releases both participants once',function()
    local c,a,v=setup();local ended=0;c:onChanged(function(_,why)if why=='danceEnd'then ended=ended+1 end end)
    assert(c:dance(a,v,2,1,4));c:tick(5.9);assert(a.busy);c:tick(6)
    assert(not a.busy and not v.busy and not a.dance and not v.dance and ended==2)
    assert(v.health==42 and a.kills==0 and not v.virtualDead);c:tick(6.1);assert(ended==2)
end)
test('actor departure releases the target without scoring',function()
    local c,a,v=setup();assert(c:dance(a,v,2,1,4));c:detach(a,3)
    assert(not v.busy and not v.dance and v.ragdolled and v.health==42 and not a.alive)
end)
test('target departure releases the actor and stale links cannot rebind',function()
    local c,a,v=setup();assert(c:dance(a,v,2,1,4));c:detach(v,3)
    local fresh=c:register('target');assert(not a.busy and not a.dance and not fresh.busy and not fresh.dance)
    c:tick(6);assert(a.kills==0 and fresh.health==100)
end)
print('PAIRED DANCE CORE TESTS '..count)
