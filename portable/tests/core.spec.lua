local ok, Core = pcall(dofile, "portable/core.lua")
assert(ok, "Portable virtual combat core must exist and load")
local count = 0
local function test(name, fn) fn();count=count+1;print("PASS core: "..name) end
local function setup()
    local c=Core.new({Damage={17,17,35},SwingCooldown={0.4,0.4,1},Startup={0.1,0.1,0.2},ActiveWindow=0.2,DownDuration=12,InteractDistance=6})
    return c,c:register("actor"),c:register("target")
end
test("swing cooldown rejects spam",function()
    local c,a=setup();assert(c:swing(a,0));assert(not c:swing(a,0.1));assert(c:swing(a,0.4))
end)
test("startup and duplicate hits preserve virtual health",function()
    local c,a,v=setup();local attack=c:swing(a,0)
    assert(not c:hit(a,v,attack,0.05));assert(v.health==100)
    assert(c:hit(a,v,attack,0.15));assert(v.health==83)
    assert(not c:hit(a,v,attack,0.16));assert(v.health==83)
end)
test("third combo strike downs target",function()
    local c,a,v=setup()
    for _,t in ipairs({0,0.5,1}) do local x=c:swing(a,t);assert(x);assert(c:hit(a,v,x,t+x.startup+0.01));c:tick(t+0.49) end
    assert(v.downed and v.ragdolled)
end)
test("old swing cannot hit after another swing starts",function()
    local c,a,v=setup();local x=c:swing(a,0);c:swing(a,0.5)
    assert(not c:hit(a,v,x,0.15));assert(v.health==100)
end)
test("carry requires owned downed target and valid distance",function()
    local c,a,v=setup();assert(not c:carry(a,v,0,1));v.downed=true;v.ragdolled=true
    assert(not c:carry(a,v,0,7));assert(not c:carry(a,v,0,0/0));assert(c:carry(a,v,0,5))
    assert(a.carrying==v and v.carriedBy==a and not v.ragdolled)
    assert(not c:swing(a,1));assert(not c:carry(a,a,1,0))
end)
test("drop restarts recoverable local ragdoll",function()
    local c,a,v=setup();v.downed=true;assert(c:carry(a,v,0,1));assert(c:drop(a,2))
    assert(not a.carrying and not v.carriedBy and v.ragdolled)
    c:tick(15);assert(not v.downed and v.health==100)
end)
test("carrier removal releases target",function()
    local c,a,v=setup();v.downed=true;assert(c:carry(a,v,0,1));c:detach(a,1)
    assert(not v.carriedBy and v.ragdolled and not a.alive)
end)
test("new record generation never reuses detached target",function()
    local c,a,v=setup();c:detach(v,0);local newer=c:register("target")
    assert(newer~=v and newer.alive);v.downed=true;assert(not c:carry(a,v,1,1))
end)
print("CORE TESTS "..count)
test("Glory requires nearby downed target",function()
    local c,a,v=setup();assert(not c:glory(a,v,0,1,2));v.downed=true;v.ragdolled=true
    assert(not c:glory(a,v,0,7,2));assert(c:glory(a,v,0,1,2));assert(a.busy and v.busy and not v.ragdolled)
end)
test("Glory completion is local and counted once",function()
    local c,a,v=setup();v.downed=true;assert(c:glory(a,v,0,1,2))
    c:tick(2.1);assert(a.kills==1 and not a.busy and v.virtualDead and v.ragdolled)
    c:tick(2.2);assert(a.kills==1);c:tick(6.2);assert(v.health==100 and not v.virtualDead)
end)
test("Glory from carry releases carry fields",function()
    local c,a,v=setup();v.downed=true;assert(c:carry(a,v,0,1));assert(c:glory(a,v,1,1,2))
    assert(not a.carrying and not v.carriedBy)
end)
test("Glory target removal frees actor without scoring",function()
    local c,a,v=setup();v.downed=true;assert(c:glory(a,v,0,1,2));c:detach(v,1);c:tick(3)
    assert(not a.busy and not a.link and a.kills==0)
end)
test("Glory actor removal frees target",function()
    local c,a,v=setup();v.downed=true;assert(c:glory(a,v,0,1,2));c:detach(a,1)
    assert(not v.busy and not v.link and v.ragdolled)
end)
print("CORE TOTAL "..count)
test("both prompts accept a briefly ragdolled target",function()
    local c,a,v=setup();v.ragdolled=true;v.downed=false
    assert(c:canCarry(a,v,1));assert(c:canGlory(a,v,1));assert(c:carry(a,v,0,1));assert(v.downed)
end)
print("CORE FINAL "..count)
